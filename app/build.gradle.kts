// امضا: از متغیرهای محیطی (GitHub Secrets) یا فایل محلی keystore.properties (خارج از مخزن) خوانده می‌شود.
val keystoreProps = Properties().apply {
    val f = rootProject.file("keystore.properties")
    if (f.exists()) f.inputStream().use { load(it) }
}
fun signingValue(env: String, key: String): String? =
    System.getenv(env)?.takeIf { it.isNotBlank() } ?: keystoreProps.getProperty(key)

val ksPath = signingValue("KEYSTORE_FILE", "storeFile")
val ksPass = signingValue("KEYSTORE_PASSWORD", "storePassword")
val ksAlias = signingValue("KEY_ALIAS", "keyAlias")
val ksKeyPass = signingValue("KEY_PASSWORD", "keyPassword")
val hasSigning = ksPath != null && file(ksPath).exists() && ksPass != null && ksAlias != null && ksKeyPass != null

