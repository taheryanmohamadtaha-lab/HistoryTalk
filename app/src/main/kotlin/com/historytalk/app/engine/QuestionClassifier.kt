package com.historytalk.app.engine

import com.historytalk.app.data.model.Cat

/** دسته‌بندی سؤال با کلیدواژه‌های فارسی (آفلاین). */
object QuestionClassifier {
    private val greetings = listOf("سلام", "درود", "وقت بخیر", "صبح بخیر", "عصر بخیر", "شب بخیر", "خسته نباشی", "حالت چطور", "احوال")
    private val intro = listOf("خودت را معرفی", "خودتو معرفی", "تو کی هستی", "تو کیستی", "کی هستی", "کیستی", "معرفی کن", "اسمت چیه", "نامت چیست", "کی هستید")

    private val rules: List<Pair<String, List<String>>> = listOf(
        Cat.CRIMES to listOf("جنایت", "کشتار", "قتل عام", "نسل کشی", "هولوکاست", "هولوکوست", "اردوگاه", "گولاگ", "اعدام", "پاکسازی", "شکنجه", "ظلم", "ستم", "بی رحم", "خشونت", "قحطی", "کشته", "ستمگر", "پشیمان", "مظلوم", "خونریز"),
        Cat.WAR to listOf("جنگ", "نبرد", "لشکر", "ارتش", "سپاه", "فتح", "حمله", "شکست", "پیروزی", "سرباز", "تاکتیک", "محاصره", "کشورگشا", "فرمانده", "جنگ ها", "سلاح"),
        Cat.POLITICS to listOf("سیاست", "حکومت", "قدرت", "پادشاه", "شاه", "امپراتور", "دولت", "قانون", "اصلاح", "انقلاب", "رهبر", "صدراعظم", "نخست وزیر", "حزب", "مجلس", "اقتصاد", "مالیات", "دیپلماس", "معاهده", "پیمان", "تاج", "سلطنت", "کشورداری", "وزیر"),
        Cat.FAMILY to listOf("خانواده", "همسر", "زن ", "فرزند", "پسر", "دختر", "برادر", "خواهر", "ازدواج", "عشق", "دوست", "پدر", "مادر", "نوه", "همدم"),
        Cat.BELIEFS to listOf("عقیده", "باور", "دین", "مذهب", "خدا", "فلسفه", "ایمان", "اندیشه", "ارزش", "اخلاق", "آزادی", "ازادی", "عدالت", "دیدگاه", "معنای", "حقیقت", "جاودان", "خوشبختی", "فضیلت", "نظرت درباره"),
        Cat.SCIENCE to listOf("علم", "دانش", "کشف", "اختراع", "نظریه", "فیزیک", "ریاضی", "پزشکی", "طب", "کتاب", "اثر", "نقاشی", "هنر", "مهندسی", "آزمایش", "نسبیت", "تحقیق", "فرمول", "اختراعات", "درس", "مدرسه", "دارالفنون"),
        Cat.LEGACY to listOf("میراث", "تاثیر", "ماندگار", "قضاوت", "نامت", "به یاد", "تاریخ درباره", "پس از مرگ", "بعد از مرگ", "جانشین", "چه شد"),
        Cat.ERA to listOf("دوران", "زمانه", "عصر", "روزگار", "جامعه", "مردم", "غذا", "لباس", "سفر", "شهر", "روزمره", "آن زمان", "در آن روزها"),
        Cat.LIFE to listOf("زندگی", "متولد", "تولد", "کودکی", "نوجوانی", "جوانی", "بزرگ شد", "مرگ", "مردی", "درگذشت", "وفات", "تحصیل", "آغاز", "شروع", "بیوگرافی", "مهم ترین تصمیم", "تصمیم"),
    )

    fun classify(question: String): String {
        val q = " " + PersianText.normalize(question) + " "
        if (q.trim().length <= 40 && greetings.any { q.contains(PersianText.normalize(it)) }) return Cat.GREETING
        if (intro.any { q.contains(PersianText.normalize(it)) }) return Cat.INTRO
        var best = Cat.GENERAL
        var bestScore = 0
        for ((cat, words) in rules) {
            val score = words.count { q.contains(PersianText.normalize(it).let { w -> if (it.endsWith(" ")) "$w " else w }) }
            if (score > bestScore) { bestScore = score; best = cat }
        }
        return best
    }
}
